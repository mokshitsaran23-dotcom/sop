export function getLanguageByCode(code) {
  if (!code) return DEFAULT_LANGUAGE;
  const normalized = code.toLowerCase();
  return SUPPORTED_LANGUAGES.find(l => 
    l.code.toLowerCase() === normalized || 
    l.shortCode.toLowerCase() === normalized ||
    normalized.startsWith(l.shortCode.toLowerCase())
  ) || DEFAULT_LANGUAGE;
}

export function getShortLangCode(code) {
  return getLanguageByCode(code).shortCode;
}
